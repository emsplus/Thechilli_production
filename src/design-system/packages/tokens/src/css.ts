import {
  chilli, charcoal, brandColors, textRoles, fontWeight, darkColors, darkShading, densities, fontFamily, grain, kdsColors, shadingFx, lightScene, darkScene, type Scene, lightColors, lightShading, motion, onHero, radius, shadow,
  spacing, typeScale, type Shading, THEME_LIGHT_ONLY,
} from './tokens';

const vars = (o: Record<string, string>) =>
  Object.entries(o).map(([k, v]) => `  --c-${k}: ${v};`).join('\n');

/** Sign-in scene variables for one theme. */
export function sceneVars(s: Scene): string {
  return Object.entries(s).filter(([, v]) => typeof v === 'string').map(([k, v]) => `  --ch-scene-${k.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase())}: ${v};`).join('\n');
}

/** Shading variables for one theme (gradients, glows, warm shadows). */
export function shadingVars(s: Shading): string {
  const [h0, h1, h2, h3] = s.heroStops;
  const [p0, p1, p2] = s.primaryStops;
  const [q0, q1, q2] = s.primaryHoverStops;
  const [t0, t1, t2] = s.tileStops;
  return [
    `  --ch-grad-hero: radial-gradient(95% 80% at 90% -10%, ${s.heroGlow} 0%, ${s.heroGlowSoft} 42%, transparent 78%), linear-gradient(162deg, ${h0} 0%, ${h1} 34%, ${h2} 68%, ${h3} 100%);`,
    `  --ch-hero-fallback: ${s.heroFallback};`,
    `  --ch-grad-hero-plain: linear-gradient(162deg, ${h0} 0%, ${h1} 34%, ${h2} 68%, ${h3} 100%);`,
    `  --ch-grad-primary: linear-gradient(180deg, ${p0} 0%, ${p1} 50%, ${p2} 100%);`,
    `  --ch-grad-primary-hover: linear-gradient(180deg, ${q0} 0%, ${q1} 50%, ${q2} 100%);`,
    `  --ch-grad-tile: linear-gradient(162deg, ${t0} 0%, ${t1} 55%, ${t2} 100%);`,
    `  --ch-grad-warm: linear-gradient(180deg, ${s.washTop} 0%, var(--c-bg) 100%);`,
    `  --ch-glow: radial-gradient(90rem 30rem at 50% -10rem, ${s.canvasGlow} 0%, transparent 70%);`,
    `  --ch-grad-page: radial-gradient(55% 60% at 12% 0%, ${s.pageGlowA} 0%, transparent 70%), radial-gradient(50% 55% at 92% 100%, ${s.pageGlowB} 0%, transparent 72%);`,
    `  --ch-shadow-tile: ${s.shadowTile};`,
    `  --ch-shadow-warm: ${s.shadowWarm};`,
  ].join('\n');
}

/**
 * Generates the full tokens.css string. `darkTheme` (default: off while THEME_LIGHT_ONLY) adds the `[data-theme='dark']` and
 * `prefers-color-scheme: dark` blocks; the always-dark `[data-kds]` kitchen subtree is emitted either way.
 */
export function buildCss({ darkTheme = !THEME_LIGHT_ONLY }: { darkTheme?: boolean } = {}): string {
  const density = (d: keyof typeof densities) => {
    const v = densities[d];
    return `  --control-h: ${v.control}px;\n  --control-pay-h: ${v.pay}px;\n  --body-size: ${v.body}px;\n  --body-lh: ${v.lineHeight}px;\n  --target-min: ${v.target}px;\n  --gap-tight: ${v.gap}px;\n  --cell-y: ${v.cellY}px;`;
  };
  const root = [
    ...Object.entries(chilli).map(([k, v]) => `  --c-chilli-${k}: ${v};`),
    ...Object.entries(charcoal).map(([k, v]) => `  --c-charcoal-${k}: ${v};`),
    ...Object.entries(brandColors).map(([k, v]) => `  --c-brand-${k}: ${v};`),
    ...Object.entries(textRoles).flatMap(([k, [s, l, w, ls]]) => [`  --text-${k}: ${s}px;`, `  --lh-${k}: ${l}px;`, `  --fw-${k}: ${w};`, `  --ls-${k}: ${ls}em;`]),
    ...Object.entries(fontWeight).map(([k, v]) => `  --weight-${k}: ${v};`),
    ...Object.entries(typeScale).flatMap(([k, [s, l]]) => [`  --text-${k}: ${s}px;`, `  --lh-${k}: ${l}px;`]),
    ...spacing.map((s) => `  --space-${s}: ${s}px;`),
    ...Object.entries(radius).map(([k, v]) => `  --radius-${k}: ${v}px;`),
    `  --shadow-pop: ${shadow.pop};`,
    `  --shadow-modal: ${shadow.modal};`,
    `  --shadow-e1: ${shadow.pop};`,
    `  --shadow-e2: ${shadow.modal};`,
    `  --font-sans: ${fontFamily.sans};`,
    `  --font-mono: ${fontFamily.mono};`,
    `  --font-display: ${fontFamily.display};`,
    `  --font-tagline: ${fontFamily.tagline};`,
    `  --dur-press: ${motion.duration.press}ms;`,
    `  --dur-fade: ${motion.duration.fade}ms;`,
    `  --dur-enter: ${motion.duration.enter}ms;`,
    `  --ease: ${motion.easing};`,
    `  --gutter: 16px;`,
    `  --hit: max(44px, var(--target-min));`,
    `  --c-on-hero: ${onHero.fg};`,
    `  --c-on-hero-muted: ${onHero.muted};`,
    `  --c-hero-ink: ${onHero.ink};`,
    `  --c-on-hero-line: ${onHero.line};`,
    `  --c-on-hero-tint: ${onHero.tint};`,
    `  --ch-scrim: linear-gradient(0deg, ${onHero.scrim} 0%, ${onHero.scrimMid} 55%, transparent 100%);`,
    `  --ch-inset-hi: ${shadingFx.insetHi};`,
    `  --ch-inset-press: ${shadingFx.insetPress};`,
    `  --ch-shadow-lift: ${shadingFx.lift};`,
    `  --ch-grain: ${grain};`,
  ].join('\n');
  const dark = `${vars(darkColors)}\n${shadingVars(darkShading)}\n${sceneVars(darkScene)}`;
  return `/* Generated by @chilli/tokens. Do not edit. */
:root {
${vars(lightColors)}
${vars(kdsColors)}
${shadingVars(lightShading)}
${sceneVars(lightScene)}
${root}
${density('touch')}
  color-scheme: light;
}
${darkTheme ? '' : `/* Light theme only: 'only light' also stops browser force-dark (Android Chrome, Samsung Internet) from re-colouring the page. */
:root { color-scheme: only light; }
`}${darkTheme ? ":root[data-theme='dark'],\n" : ''}[data-kds] {
${dark}
  color-scheme: dark;
}
${darkTheme ? `@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${dark.replace(/^ {2}/gm, '    ')}
    color-scheme: dark;
  }
}
` : ''}:root[data-density='touch'] {
${density('touch')}
}
:root[data-density='comfortable'] {
${density('comfortable')}
}
:root[data-density='compact'] {
${density('compact')}
}
:root[data-density='far'],
[data-density='far'] {
${density('far')}
}
@media (min-width: 768px) {
  :root { --gutter: 24px; }
}
/* Motion: reduced-motion turns off everything except state changes. */
@media (prefers-reduced-motion: reduce) {
  :root { --dur-press: 0ms; --dur-fade: 0ms; --dur-enter: 0ms; }
}
:root[data-motion='off'] { --dur-press: 0ms; --dur-fade: 0ms; --dur-enter: 0ms; }
`;
}

const LATIN = 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD';
const LATIN_EXT = 'U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF';

/**
 * Font files shipped with @chilli/tokens (style guide v1.0 final): Inter variable (UI/body), JetBrains Mono variable (amounts, KOT),
 * Poppins 700/800 (headings, wordmark), Montserrat 600 (tagline). latin-ext carries the rupee sign and loads only when a page uses it.
 */
export const fontFiles = [
  { pkg: '@fontsource-variable/inter', family: 'Inter Variable', file: 'inter-latin-wght-normal.woff2', weight: '100 900', variable: true, range: LATIN },
  { pkg: '@fontsource-variable/inter', family: 'Inter Variable', file: 'inter-latin-ext-wght-normal.woff2', weight: '100 900', variable: true, range: LATIN_EXT },
  { pkg: '@fontsource-variable/jetbrains-mono', family: 'JetBrains Mono Variable', file: 'jetbrains-mono-latin-wght-normal.woff2', weight: '100 800', variable: true, range: LATIN },
  { pkg: '@fontsource-variable/jetbrains-mono', family: 'JetBrains Mono Variable', file: 'jetbrains-mono-latin-ext-wght-normal.woff2', weight: '100 800', variable: true, range: LATIN_EXT },
  { pkg: '@fontsource/poppins', family: 'Poppins', file: 'poppins-latin-700-normal.woff2', weight: '700', variable: false, range: LATIN },
  { pkg: '@fontsource/poppins', family: 'Poppins', file: 'poppins-latin-800-normal.woff2', weight: '800', variable: false, range: LATIN },
  { pkg: '@fontsource/montserrat', family: 'Montserrat', file: 'montserrat-latin-600-normal.woff2', weight: '600', variable: false, range: LATIN },
] as const;

/** @font-face rules for `@chilli/tokens/fonts.css` (urls relative to dist/). */
export function buildFontsCss(): string {
  return `/* Generated by @chilli/tokens. Inter, JetBrains Mono, Poppins, Montserrat (OFL), self-hosted woff2, no CDN. */\n` + fontFiles.map((f) =>
    `@font-face{font-family:'${f.family}';font-style:normal;font-display:swap;font-weight:${f.weight};src:${f.variable ? `url(./fonts/${f.file}) format('woff2-variations'),` : ''}url(./fonts/${f.file}) format('woff2');unicode-range:${f.range}}`,
  ).join('\n') + '\n';
}
