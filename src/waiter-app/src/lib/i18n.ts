export const DICT: Record<Lang, Partial<Record<Key, string>>> = { en, hi };

/** Pure translate (testable): language, key, optional `{var}` values. Unknown hi key -> en; unknown key -> the key. */
export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  const s = DICT[lang][key] ?? en[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
}

export const isLang = (v: unknown): v is Lang => v === "en" || v === "hi";

const KEY = "waiter.lang";
const EV = "waiter-lang";
let current: Lang | null = null;
export function getLang(): Lang {
  if (!languagesEnabled()) return "en";
  if (current) return current;
  let v: string | null = null;
  try { v = localStorage.getItem(KEY); } catch { /* ignore */ }
  return (current = isLang(v) ? v : "en");
}
export function setLang(l: Lang) {
  if (!languagesEnabled()) return;
  current = l;
  try { localStorage.setItem(KEY, l); } catch { /* ignore */ }
  try { document.documentElement.lang = l; } catch { /* ignore */ }
  window.dispatchEvent(new Event(EV));
}
export function useLang(): Lang {
  return useSyncExternalStore((cb) => { window.addEventListener(EV, cb); return () => window.removeEventListener(EV, cb); }, getLang, () => "en" as Lang);
}
export function useT() {
  const lang = useLang();
  return useCallback((key: Key, vars?: Record<string, string | number>) => translate(lang, key, vars), [lang]);
}
